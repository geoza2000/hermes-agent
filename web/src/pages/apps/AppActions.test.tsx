// @vitest-environment jsdom
import { act } from "react";
import { createRoot } from "react-dom/client";
import { afterEach, expect, it, vi } from "vitest";
import { AppActions } from "./AppActions";
const fetchJSON = vi.hoisted(() => vi.fn());
vi.mock("@/lib/api", () => ({ fetchJSON, HERMES_BASE_PATH: "/proxy" }));
(globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }).IS_REACT_ACT_ENVIRONMENT = true;
afterEach(() => { vi.restoreAllMocks(); fetchJSON.mockReset(); });
it("publishes only the immutable reviewed revision after explicit confirmation", async () => {
  const host = document.createElement("div"); const root = createRoot(host); const published = vi.fn();
  fetchJSON.mockImplementation(async (path: string) => path.includes('/review') ? { revision: "sha256:reviewed", path: "/apps-cap/test/", expires_at: Date.now() / 1000 + 1000 } : { app: { versions: [] } });
  await act(async () => root.render(<AppActions profile="personal" slug="notes" onPublished={published} />));
  const button = (text: string) => Array.from(host.querySelectorAll("button")).find(b => b.textContent === text)!;
  expect(host.textContent).not.toContain("Publish reviewed draft");
  await act(async () => button("Preview draft").click());
  expect(fetchJSON).toHaveBeenCalledWith("/api/apps/notes/review?profile=personal", expect.objectContaining({ method: "POST" }));
  expect(host.querySelector("iframe")?.getAttribute("src")).toBe("/proxy/apps-cap/test/");
  expect(host.querySelector("iframe")?.getAttribute("sandbox")).not.toContain("allow-same-origin");
  const confirm = vi.spyOn(window, "confirm").mockReturnValue(false);
  await act(async () => button("Publish reviewed draft").click());
  expect(published).not.toHaveBeenCalled();
  confirm.mockReturnValue(true);
  await act(async () => button("Publish reviewed draft").click());
  expect(fetchJSON).toHaveBeenCalledWith("/api/apps/notes/publish?profile=personal", expect.objectContaining({ method: "POST", body: JSON.stringify({ revision: "sha256:reviewed", note: "Approved from dashboard draft preview" }) }));
  expect(published).toHaveBeenCalledTimes(1);
  expect(host.querySelector("iframe")).toBeNull();
  await act(async () => root.unmount());
});
it("invalidates a reviewed revision on profile change, expiry and failed mutation", async () => {
  const host = document.createElement("div"); const root = createRoot(host);
  fetchJSON.mockResolvedValue({ revision: "r1", path: "/apps-cap/one/", expires_at: Date.now() / 1000 + 100 });
  const button = (text: string) => Array.from(host.querySelectorAll("button")).find(b => b.textContent === text)!;
  await act(async () => root.render(<AppActions profile="a" slug="notes" onPublished={vi.fn()} />));
  await act(async () => button("Preview draft").click());
  await act(async () => root.render(<AppActions profile="b" slug="notes" onPublished={vi.fn()} />));
  expect(host.querySelector("iframe")).toBeNull();
  fetchJSON.mockResolvedValue({ revision: "r2", path: "/apps-cap/two/", expires_at: 1 });
  await act(async () => button("Preview draft").click());
  vi.spyOn(window, "confirm").mockReturnValue(true);
  await act(async () => button("Publish reviewed draft")?.click());
  expect(fetchJSON.mock.calls.some(([url]) => String(url).includes('/publish'))).toBe(false);
  await act(async () => root.unmount());
});
it("selects rollback targets from the actual manifest and requires confirmation", async () => {
  const host = document.createElement("div"); const root = createRoot(host);
  fetchJSON.mockResolvedValue({ app: { current_version: 2, versions: [{ number: 1, note: "First", published_at: 1 }, { number: 2, note: "Current", published_at: 2 }] } });
  await act(async () => root.render(<AppActions profile="a" slug="notes" onPublished={vi.fn()} />));
  const button = (text: string) => Array.from(host.querySelectorAll("button")).find(b => b.textContent === text)!;
  await act(async () => button("Version history").click());
  expect(host.querySelector('select')?.textContent).toContain("v1 — First");
  const confirm = vi.spyOn(window, 'confirm').mockReturnValue(false);
  await act(async () => button("Restore version").click());
  expect(fetchJSON.mock.calls.some(([url]) => String(url).includes('/rollback'))).toBe(false);
  confirm.mockReturnValue(true);
  await act(async () => button("Restore version").click());
  expect(fetchJSON).toHaveBeenCalledWith('/api/apps/notes/rollback?profile=a', expect.objectContaining({ body: JSON.stringify({ version: 1 }) }));
  await act(async () => root.unmount());
});
